<?php
    // Incremento / Decremento operatori

    $contatore = 0;

    $contatore++; // = $contatore + 1
    echo("$contatore <br>");

    $contatore--; // = $contatore - 1
    echo("$contatore <br>");

    $contatore+=2; // = $contatore + 2
    echo("$contatore <br>");

    $contatore-=2; // = $contatore - 2
    echo($contatore);
?>