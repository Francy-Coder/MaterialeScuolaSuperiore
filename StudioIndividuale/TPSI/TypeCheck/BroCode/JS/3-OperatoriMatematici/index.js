// Ordine degli operatori 
    // () > ** > * > / > + > -

let studenti = 30;

console.log(studenti);

studenti = studenti + 1;
console.log(studenti);

studenti = studenti - 1;
console.log(studenti);

studenti = studenti * 2;
console.log(studenti);

studenti = studenti / 2;
console.log(studenti);

studenti = studenti ** 2;
console.log(studenti);

studenti = studenti % 2;
console.log(studenti);

/*
x += 1 --> x = x + 1
x -= 1 --> x = x - 1
x *= 1 --> x = x * 1
x /= 1 --> x = x / 1
x **= 1 --> x = x ** 1
x %= 1 --> x = x % 1

studenti++; --> studenti = studenti - 1
studenti--; --> studenti = studenti + 1
*/